    std::vector<std::pair<uint32_t, MarkerIndex::Floor>> Shipped() {
        std::vector<std::pair<uint32_t, MarkerIndex::Floor>> out;
        for (const Row& row : GROUPS)
            out.push_back({ row.group, row.floorGroup ? MarkerIndex::Floor::Under(row.floorGroup, row.floor) : MarkerIndex::Floor::Over() });
        return out;
    }

    Of OfGroup(uint32_t group, const MarkerIndex::Index& index) {
        auto row = std::lower_bound(std::begin(GROUPS), std::end(GROUPS), group,
            [](const Row& r, uint32_t g) { return r.group < g; });
        if (row == std::end(GROUPS) || row->group != group)
            return {};
        if (!row->floorGroup)
            return { true, MarkerIndex::Floor::Over() };
        if (!index.HasFloor(row->floorGroup, row->floor))
            return {};
        return { true, MarkerIndex::Floor::Under(row->floorGroup, row->floor) };
    }

    Of At(uint32_t group, const MarkerIndex::Index& index, const std::unordered_set<int>& types,
          int map, double x, double y, double reach) {
        Of of = OfGroup(group, index);
        if (of.known)
            return of;
        if (!index.UnderNear(types, map, x, y, reach))
            return { true, MarkerIndex::Floor::Over() };
        return {};
    }
